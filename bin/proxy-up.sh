#!/usr/bin/env bash
# bin/proxy-up.sh — spin up the hotspot-proxy stack for omo.
#
# What this does:
#   1. Generates a tinyproxy config (with a random BasicAuth password) at
#      .proxy/tinyproxy.conf on first run. Subsequent runs reuse it.
#   2. Boots tinyproxy listening on 127.0.0.1:8888, forwarding HTTP+HTTPS
#      CONNECT traffic out via whatever network the laptop is on (your
#      phone hotspot, in this case).
#   3. Boots a Cloudflare quick-tunnel (cloudflared) that exposes the
#      local proxy as a public https://*.trycloudflare.com URL — no
#      port-forward / no Cloudflare account needed.
#   4. Writes the resulting URL + credentials into .env (under the
#      BROWSERBASE_PROXY_* keys), backing up the previous .env to
#      .env.bak first. The omo runner auto-detects external mode the
#      moment it sees BROWSERBASE_PROXY_SERVER set.
#   5. Stays in the foreground; ctrl-C cleanly kills both processes.
#
# Usage:
#   npm run proxy:up
#   # in another terminal:
#   npm start
#
# Requirements (one-time):
#   brew install tinyproxy cloudflared
#
# Quick-tunnel URLs change every time cloudflared restarts. The script
# rewrites .env on each run so just remember to restart `npm start` after
# bringing the proxy up.

set -euo pipefail

# Repo root (this script lives in bin/, so root is its parent).
ROOT="$( cd -- "$( dirname -- "${BASH_SOURCE[0]}" )/.." &> /dev/null && pwd )"
cd "$ROOT"

PROXY_DIR=".proxy"
CONF="$PROXY_DIR/tinyproxy.conf"
PIDFILE="$PROXY_DIR/tinyproxy.pid"
CREDS="$PROXY_DIR/credentials"
TUN_LOG="$PROXY_DIR/cloudflared.log"
READY_MARKER="$PROXY_DIR/ready"
PORT="${PROXY_PORT:-8888}"

mkdir -p "$PROXY_DIR"
# Clear any stale ready-marker so wrappers (start-with-proxy.sh) can
# detect when this run actually finishes its setup.
rm -f "$READY_MARKER"

# ─── 1. Sanity-check binaries ──────────────────────────────────────────
need() {
  if ! command -v "$1" >/dev/null 2>&1; then
    echo "[proxy-up] missing '$1' — install with:  brew install $2"
    exit 1
  fi
}
need tinyproxy tinyproxy
need cloudflared cloudflared

# ─── 2. Refuse if the port is already busy ─────────────────────────────
if lsof -nP -iTCP:"$PORT" -sTCP:LISTEN >/dev/null 2>&1; then
  echo "[proxy-up] port $PORT already in use — stop the other process first."
  echo "           tip: brew services stop tinyproxy   (if started via brew)"
  echo "           tip: lsof -nP -iTCP:$PORT -sTCP:LISTEN   (find the offender)"
  exit 1
fi

# ─── 3. Generate / load BasicAuth credentials ──────────────────────────
if [ ! -f "$CREDS" ]; then
  PROXY_USERNAME="omo"
  PROXY_PASSWORD="$(openssl rand -hex 24)"
  printf 'PROXY_USERNAME=%s\nPROXY_PASSWORD=%s\n' "$PROXY_USERNAME" "$PROXY_PASSWORD" > "$CREDS"
  chmod 600 "$CREDS"
  echo "[proxy-up] generated fresh credentials → $CREDS"
fi
# shellcheck disable=SC1090
. "$CREDS"

# ─── 4. Write tinyproxy config ─────────────────────────────────────────
cat > "$CONF" <<EOF
# Auto-generated by bin/proxy-up.sh — edit at your own risk.
Port $PORT
Listen 127.0.0.1
Timeout 600
LogLevel Info
PidFile "$ROOT/$PIDFILE"

# Allow CONNECT for HTTPS (Browserbase will tunnel TLS through us).
ConnectPort 443
ConnectPort 80
ConnectPort 8443

# Local-only access; the public surface is the Cloudflare tunnel.
Allow 127.0.0.1
BasicAuth $PROXY_USERNAME $PROXY_PASSWORD
EOF
echo "[proxy-up] wrote $CONF"

# ─── 5. Cleanup hook (runs on ctrl-C / exit) ───────────────────────────
TINYPROXY_PID=""
CLOUDFLARED_PID=""
cleanup() {
  echo
  echo "[proxy-up] shutting down…"
  rm -f "$READY_MARKER"
  [ -n "$CLOUDFLARED_PID" ] && kill "$CLOUDFLARED_PID" 2>/dev/null || true
  [ -n "$TINYPROXY_PID"   ] && kill "$TINYPROXY_PID"   2>/dev/null || true
  wait 2>/dev/null || true
  exit 0
}
trap cleanup INT TERM

# ─── 6. Boot tinyproxy in the background ───────────────────────────────
echo "[proxy-up] starting tinyproxy on 127.0.0.1:$PORT"
tinyproxy -d -c "$CONF" &
TINYPROXY_PID=$!

# Give it a beat, then sanity-check it's actually listening.
sleep 1
if ! kill -0 "$TINYPROXY_PID" 2>/dev/null; then
  echo "[proxy-up] tinyproxy died on startup — check the config above."
  exit 1
fi

# ─── 7. Boot the Cloudflare quick-tunnel ───────────────────────────────
echo "[proxy-up] opening Cloudflare quick-tunnel…"
: > "$TUN_LOG"
cloudflared tunnel --no-autoupdate --url "http://localhost:$PORT" \
  > "$TUN_LOG" 2>&1 &
CLOUDFLARED_PID=$!

# Wait for the public URL to appear in the cloudflared log.
TUN_URL=""
for _ in $(seq 1 40); do
  TUN_URL="$(grep -oE 'https://[a-z0-9-]+\.trycloudflare\.com' "$TUN_LOG" 2>/dev/null | head -n1 || true)"
  if [ -n "$TUN_URL" ]; then break; fi
  if ! kill -0 "$CLOUDFLARED_PID" 2>/dev/null; then
    echo "[proxy-up] cloudflared died on startup — log:"
    tail -n 20 "$TUN_LOG"
    cleanup
  fi
  sleep 1
done
if [ -z "$TUN_URL" ]; then
  echo "[proxy-up] gave up waiting for tunnel URL — last 20 lines of log:"
  tail -n 20 "$TUN_LOG"
  cleanup
fi
echo "[proxy-up] tunnel ready: $TUN_URL"

# ─── 8. Self-test the full path ────────────────────────────────────────
echo "[proxy-up] self-test → $TUN_URL → tinyproxy → carrier exit IP…"
EXIT_IP="$(curl --max-time 15 -fsS \
  -x "$TUN_URL" -U "$PROXY_USERNAME:$PROXY_PASSWORD" \
  https://ifconfig.me 2>/dev/null || true)"
if [ -n "$EXIT_IP" ]; then
  echo "[proxy-up] self-test ok · egress IP = $EXIT_IP"
else
  echo "[proxy-up] self-test FAILED — Browserbase will likely fall back."
  echo "           common causes: hotspot disconnected, BasicAuth mismatch,"
  echo "           or carrier blocking outbound 443."
fi

# ─── 9. Patch .env with the new tunnel URL ─────────────────────────────
ENV_FILE=".env"
if [ ! -f "$ENV_FILE" ]; then
  echo "[proxy-up] no .env found at $ENV_FILE — creating one."
  : > "$ENV_FILE"
fi
cp "$ENV_FILE" "$ENV_FILE.bak"

# Strip any prior BROWSERBASE_PROXY_* lines, then append fresh values.
TMP="$(mktemp)"
grep -vE '^BROWSERBASE_PROXY_(SERVER|USERNAME|PASSWORD)=' "$ENV_FILE" > "$TMP" || true
{
  cat "$TMP"
  printf '\n# Managed by bin/proxy-up.sh (regenerated each run)\n'
  printf 'BROWSERBASE_PROXY_SERVER=%s\n'   "$TUN_URL"
  printf 'BROWSERBASE_PROXY_USERNAME=%s\n' "$PROXY_USERNAME"
  printf 'BROWSERBASE_PROXY_PASSWORD=%s\n' "$PROXY_PASSWORD"
} > "$ENV_FILE"
rm -f "$TMP"
echo "[proxy-up] patched $ENV_FILE (backup at $ENV_FILE.bak)"

# Signal to bin/start-with-proxy.sh (or any other waiter) that the proxy
# stack is up and .env has the fresh URL.
touch "$READY_MARKER"

# ─── 10. Print summary + how to verify ─────────────────────────────────
cat <<EOM

──────────────────────────────────────────────────────────────────────
 proxy stack is live:

   tunnel  : $TUN_URL
   local   : http://127.0.0.1:$PORT  (BasicAuth $PROXY_USERNAME / …)
   exit IP : ${EXIT_IP:-unknown}

 Now restart omo so it picks up the new .env:
   (in another terminal)  npm start

 Verify Browserbase is actually exiting through your hotspot:
   ask the agent to open https://ifconfig.me — the IP should match
   ${EXIT_IP:-your phone}.

 Ctrl-C this terminal to tear the proxy down. .env will keep pointing
 at the (now dead) tunnel URL until you re-run \`npm run proxy:up\`,
 at which point the omo runner falls back to Browserbase's builtin
 rotating pool until you restart it.
──────────────────────────────────────────────────────────────────────

EOM

# ─── 11. Block until either daemon dies / user ctrl-Cs ─────────────────
wait -n "$TINYPROXY_PID" "$CLOUDFLARED_PID" || true
echo "[proxy-up] one of the daemons exited — tearing down the rest."
cleanup
